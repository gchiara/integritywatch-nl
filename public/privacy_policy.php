                <p><strong>b) Technische en analytische gegevens:</strong></p>
                <ul>
                <li>IP-adres (waar mogelijk ingekort of geanonimiseerd)</li>
                <li>type apparaat</li>
                <li>besturingssysteem</li>
                <li>internetbrowser en browsertaal</li>
                <li>datum en tijd van uw bezoek</li>
                <li>bekeken pagina's en duur van uw bezoek</li>
                <li>de website waarvandaan u het Platform bezocht</li>
                </ul>
                <p>Wij verwerken geen bijzondere persoonsgegevens van bezoekers, zoals gegevens over gezondheid, religie of afkomst.</p>
                <h3>4. Doelen en grondslagen</h3>
                <p>Wij gebruiken de gegevens voor:</p>
                <ul>
                <li>het beantwoorden van uw vragen;</li>
                <li>het technisch onderhoud van het Platform;</li>
                <li>statistische analyse van bezoekersaantallen en het gebruik van de inhoud;</li>
                <li>het verbeteren van de werking en gebruiksvriendelijkheid van het Platform;</li>
                <li>de beveiliging van onze systemen;</li>
                <li>het nakomen van wettelijke verplichtingen.</li>
                </ul>
                <p>Wij verwerken gegevens op basis van:</p>
                <ul>
                <li>uw <strong>toestemming</strong> (artikel 6 lid 1 sub a AVG), bijvoorbeeld voor analytische cookies;</li>
                <li>ons <strong>gerechtvaardigd belang</strong> bij het beheren, beveiligen en verbeteren van het Platform en het beantwoorden van uw vragen (artikel 6 lid 1 sub f AVG);</li>
                <li>een <strong>wettelijke verplichting</strong> (artikel 6 lid 1 sub c AVG).</li>
                </ul>
                <h3>5. Gegevens over politici en publieke ambtsdragers</h3>
                <p>Op het Platform publiceren wij informatie over politici en andere publieke ambtsdragers, zoals nevenfuncties, geschenken, reizen en agenda's. Deze gegevens halen wij uit openbare bronnen, zoals de registers van de Tweede en Eerste Kamer en openbaar gepubliceerde agenda's. Wij verkrijgen deze gegevens dus niet van de betrokkenen zelf.</p>
                <p>Wij verwerken deze gegevens op basis van ons gerechtvaardigd belang (artikel 6 lid 1 sub f AVG): het publiek inzicht geven in de integriteit en transparantie van het openbaar bestuur. Wij publiceren alleen gegevens als die verband houden met de publieke functie van de betrokkene.</p>
                <h3>6. Cookies, Google Analytics en Google Tag Manager</h3>
                <p>Het Platform gebruikt functionele cookies die nodig zijn om de website te laten werken, en analytische cookies om het gebruik te meten en de website te verbeteren. Analytische cookies plaatsen wij alleen als u daarvoor toestemming geeft via de cookiebanner. U kunt uw toestemming altijd intrekken via de cookie-instellingen. U kunt cookies ook blokkeren of verwijderen via uw browserinstellingen.</p>
                <p>Voor het meten van bezoekersaantallen en het analyseren van het gebruik gebruiken wij <strong>Google Analytics</strong>. Google Analytics maakt gebruik van cookies en vergelijkbare technieken. De informatie die daarmee wordt verzameld, kan worden opgeslagen op servers van Google LLC.</p>
                <p><strong>Google Tag Manager</strong> gebruiken wij om analytische en andere tags op de website te beheren. Google Tag Manager verzamelt zelf geen persoonsgegevens, maar zorgt ervoor dat andere hulpmiddelen worden geactiveerd.</p>
                <h3>7. Delen met derden</h3>
                <p>Wij verkopen uw persoonsgegevens niet en delen ze niet met derden voor marketingdoeleinden. Uw gegevens kunnen toegankelijk zijn voor:</p>
                <ul>
                <li>aanbieders van technische diensten en hosting;</li>
                <li>aanbieders van analysediensten (zoals Google Analytics);</li>
                <li>bevoegde overheidsinstanties, als de wet, een rechterlijke uitspraak of een ander bindend besluit dat vereist.</li>
                </ul>
                <p>Partijen die in onze opdracht gegevens verwerken, mogen deze alleen gebruiken voor de afgesproken doelen. TI-NL blijft verantwoordelijk voor deze verwerkingen.</p>
