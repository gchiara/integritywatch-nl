                <p>U bent niet verplicht persoonsgegevens te verstrekken, tenzij dat nodig is om uw vraag te beantwoorden of een bepaalde dienst te leveren.</p>
                <h3>3. Welke gegevens wij verwerken</h3>
                <p><strong>a) Persoonsgegevens die u zelf verstrekt:</strong></p>
                <ul>
                <li>voor- en achternaam</li>
                <li>e-mailadres</li>
                <li>organisatie of instelling (indien opgegeven)</li>
                <li>de inhoud van uw bericht of vraag</li>
