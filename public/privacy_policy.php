                <h3>2. Hoe wij gegevens verzamelen</h3>
                <p>Wij verzamelen gegevens op twee manieren:</p>
                <li><strong>rechtstreeks</strong>, wanneer u ze zelf aan ons geeft, bijvoorbeeld via een contactformulier, een inschrijving of andere communicatie;</li>
