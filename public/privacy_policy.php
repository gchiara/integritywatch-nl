                <p>Google kan gegevens verwerken in de Verenigde Staten. Deze doorgifte vindt plaats op basis van het EU-VS Data Privacy Framework, waaronder Google LLC is gecertificeerd, of op basis van standaardcontractbepalingen van de Europese Commissie.</p>
                <h3>9. Bewaartermijnen</h3>
                <p>Wij bewaren gegevens niet langer dan nodig is voor het doel waarvoor ze zijn verzameld, tenzij de wet een langere bewaartermijn voorschrijft.</p>
                <h3>10. Beveiliging</h3>
                <p>Wij nemen passende technische en organisatorische maatregelen om gegevens te beschermen tegen onbevoegde toegang, verlies, misbruik of wijziging.</p>
                <h3>11. Geautomatiseerde besluitvorming</h3>
                <p>Wij nemen geen besluiten op basis van uitsluitend geautomatiseerde verwerking die voor u aanzienlijke gevolgen kunnen hebben.</p>
                <h3>12. Uw rechten</h3>
                <p>Op grond van de AVG heeft u de volgende rechten:</p>
                <ul>
                <li>inzage in uw persoonsgegevens;</li>
                <li>correctie van onjuiste gegevens;</li>
                <li>verwijdering van uw gegevens, als aan de voorwaarden is voldaan;</li>
                <li>beperking van de verwerking;</li>
                <li>bezwaar tegen de verwerking;</li>
                <li>overdracht van uw gegevens in een machineleesbaar formaat (dataportabiliteit);</li>
                <li>intrekking van uw toestemming, als de verwerking op toestemming is gebaseerd.</li>
                </ul>
